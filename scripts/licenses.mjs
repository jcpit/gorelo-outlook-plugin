import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Reviewed, bounded list: all direct runtime dependencies and the two bundled
// MSAL/Font Awesome support packages. Version changes require explicit review.
export const LICENSE_MANIFEST = [
  { name: '@azure/msal-browser', version: '5.25.1', spdx: 'MIT', file: 'LICENSE', direct: true, upstream: 'https://github.com/AzureAD/microsoft-authentication-library-for-js' },
  { name: '@azure/msal-common', version: '16.14.2', spdx: 'MIT', file: 'LICENSE', direct: false, upstream: 'https://github.com/AzureAD/microsoft-authentication-library-for-js' },
  { name: '@fortawesome/free-solid-svg-icons', version: '6.7.2', spdx: '(CC-BY-4.0 AND MIT)', file: 'LICENSE.txt', direct: true, upstream: 'https://github.com/FortAwesome/Font-Awesome' },
  { name: '@fortawesome/fontawesome-common-types', version: '6.7.2', spdx: 'MIT', file: 'LICENSE.txt', direct: false, upstream: 'https://github.com/FortAwesome/Font-Awesome' },
  { name: 'express', version: '5.2.1', spdx: 'MIT', file: 'LICENSE', direct: true, upstream: 'https://github.com/expressjs/express' },
  { name: 'jose', version: '6.2.12', spdx: 'MIT', file: 'LICENSE.md', direct: true, upstream: 'https://github.com/panva/jose' },
  { name: 'sanitize-html', version: '2.17.7', spdx: 'MIT', file: 'LICENSE', direct: true, upstream: 'https://github.com/apostrophecms/apostrophe/tree/main/packages/sanitize-html' },
  { name: 'zod', version: '4.6.5', spdx: 'MIT', file: 'LICENSE', direct: true, upstream: 'https://github.com/colinhacks/zod' },
];

export const LICENSE_OUTPUT = 'public/licenses/npm-dependencies.md';
const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const readJson = async (path) => JSON.parse(await readFile(path, 'utf8'));

export async function renderLicenses(root = projectRoot) {
  const metadata = await readJson(join(root, 'package.json'));
  const lock = await readJson(join(root, 'package-lock.json'));
  const direct = LICENSE_MANIFEST.filter((entry) => entry.direct).map((entry) => entry.name).sort();
  if (JSON.stringify(Object.keys(metadata.dependencies ?? {}).sort()) !== JSON.stringify(direct)) {
    throw new Error('License manifest must cover exactly all direct package.json dependencies; review scripts/licenses.mjs.');
  }

  let output = '# npm dependency licenses\n\n'
    + 'Generated by `npm run licenses:update`; do not edit manually.\n\n'
    + 'Scope: all direct runtime dependencies plus @azure/msal-common and '
    + '@fortawesome/fontawesome-common-types. This is not a recursive inventory of all server transitive dependencies.\n\n'
    + 'SPDX labels are package metadata; each complete installed license/notice is reproduced unchanged below. '
    + 'Font Awesome notices also describe font licensing, even though this application uses SVG icons.\n';

  for (const entry of LICENSE_MANIFEST) {
    const source = `node_modules/${entry.name}/${entry.file}`;
    const installed = await readJson(join(root, 'node_modules', entry.name, 'package.json'));
    if (installed.name !== entry.name || installed.version !== entry.version
      || lock.packages?.[`node_modules/${entry.name}`]?.version !== entry.version) {
      throw new Error(`License manifest version mismatch for ${entry.name}; review installed/locked versions and scripts/licenses.mjs.`);
    }
    if (entry.direct && lock.packages?.['']?.dependencies?.[entry.name] !== metadata.dependencies[entry.name]) {
      throw new Error(`package.json/package-lock.json dependency mismatch for ${entry.name}.`);
    }
    if (installed.license !== entry.spdx) {
      throw new Error(`License manifest SPDX mismatch for ${entry.name}; review scripts/licenses.mjs.`);
    }
    // Do not trim, reflow, normalize line endings, or omit sections of notices.
    const license = await readFile(join(root, source), 'utf8');
    if (!license.length) throw new Error(`Empty source license: ${source}`);
    const fence = '`'.repeat(Math.max(3, ...[...license.matchAll(/`+/g)].map((match) => match[0].length + 1)));
    output += `\n## ${entry.name} — ${entry.version}\n\n`
      + `- SPDX: \`${entry.spdx}\`\n`
      + `- Source: \`${source}\`\n`
      + `- Upstream: ${entry.upstream}\n`
      + `- npm: https://www.npmjs.com/package/${entry.name}/v/${entry.version}\n\n`
      + `${fence}text\n${license}\n${fence}\n`;
  }
  return output;
}

export async function packageLicenses(root = projectRoot, { write = false } = {}) {
  const expected = await renderLicenses(root);
  const destination = join(root, LICENSE_OUTPUT);
  if (write) {
    await mkdir(dirname(destination), { recursive: true });
    await writeFile(destination, expected);
    return;
  }
  let actual;
  try {
    actual = await readFile(destination, 'utf8');
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }
  if (actual !== expected) {
    throw new Error(`${LICENSE_OUTPUT} is missing or stale; run npm run licenses:update and commit the reviewed output.`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args.length > 1 || (args.length === 1 && !['--write', '--check'].includes(args[0]))) {
      throw new Error('Usage: node scripts/licenses.mjs [--check|--write] (default: --check)');
    }
    await packageLicenses(projectRoot, { write: args[0] === '--write' });
    console.log(args[0] === '--write' ? `Updated ${LICENSE_OUTPUT}` : 'Dependency licenses are current.');
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
